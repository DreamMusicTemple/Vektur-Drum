#!/usr/bin/env node
// Vektur Drum — one user manual for every app.
//   node tools/gen_manual.js
// Source: web/src/manual.js (shown in the web app's SETTINGS → MANUAL). Writes:
//   native/Sources/VekturDrumCore/Manual+Generated.swift   the native app's manual (Settings → Manual), as Markdown blocks
//   docs/MANUAL.md                                         the same manual as a document
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const MANUAL = new Function(fs.readFileSync(path.join(ROOT, 'web/src/manual.js'), 'utf8') + '\nreturn MANUAL;')();
const ent = s => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&nbsp;/g, ' ');
const inline = s => ent(s.replace(/<b>(.*?)<\/b>/gs, '**$1**').replace(/<i>(.*?)<\/i>/gs, '*$1*').replace(/<a href="([^"]+)">(.*?)<\/a>/gs, '[$2]($1)').replace(/\s*\n\s*/g, ' ')).trim();
/** HTML of one section → Markdown blocks (a paragraph, or a list item starting "- "). */
function blocks(html) {
  const out = [];
  const re = /<p>([\s\S]*?)<\/p>|<ul>([\s\S]*?)<\/ul>/g; let m, seen = 0;
  while ((m = re.exec(html))) {
    if (m[1] != null) out.push(inline(m[1]));
    else for (const li of m[2].match(/<li>[\s\S]*?<\/li>/g) || []) out.push('- ' + inline(li.slice(4, -5)));
    seen += m[0].length;
  }
  const rest = html.replace(re, '').replace(/<[^>]+>/g, '').trim();
  if (rest) throw new Error('manual: text outside <p>/<ul>: ' + rest.slice(0, 60));
  if (out.some(b => /<\w/.test(b))) throw new Error('manual: unsupported tag in ' + out.find(b => /<\w/.test(b)).slice(0, 60));
  return out;
}
const secs = MANUAL.map(([title, html]) => ({ title, blocks: blocks(html) }));
const sw = s => JSON.stringify(s);
fs.writeFileSync(path.join(ROOT, 'native/Sources/VekturDrumCore/Manual+Generated.swift'), `// Generated by tools/gen_manual.js from web/src/manual.js — do not edit.
// The user manual, identical to the web app's. Each block is Markdown: a paragraph, or a list item starting "- ".
// SwiftUI: Text(AttributedString(markdown: block)) per block; list items with a bullet.

public struct ManualSection: Sendable, Identifiable {
    public let title: String
    public let blocks: [String]
    public var id: String { title }
}

public enum UserManual {
    public static let sections: [ManualSection] = [
${secs.map(s => `        ManualSection(title: ${sw(s.title)}, blocks: [\n${s.blocks.map(b => '            ' + sw(b) + ',').join('\n')}\n        ]),`).join('\n')}
    ]
}
`);
fs.writeFileSync(path.join(ROOT, 'docs/MANUAL.md'), `# Vektur Drum — User Manual\n\n_Generated from web/src/manual.js (the same text as SETTINGS → MANUAL in the web and native apps)._\n\n` +
  secs.map((s, i) => `${i ? '' : ''}## ${s.title}\n\n` + s.blocks.map((b, j) => b + (b.startsWith('- ') && s.blocks[j + 1] && s.blocks[j + 1].startsWith('- ') ? '\n' : '\n\n')).join('')).join(''));
console.log(`manual: ${secs.length} sections, ${secs.reduce((n, s) => n + s.blocks.length, 0)} blocks → Swift and docs/MANUAL.md`);

// ---- colour themes (web/src/appearance.js) → native/Sources/VekturDrumCore/Appearance+Generated.swift
{
  const src = fs.readFileSync(path.join(ROOT, 'web/src/appearance.js'), 'utf8');
  const decl = src.slice(src.indexOf('const THEMES'), src.indexOf('function themeOf'));
  const { THEMES, CHASSIS, STRIPS } = new Function(decl + '\nreturn { THEMES, CHASSIS, STRIPS };')();
  const stepDecl = src.slice(src.indexOf('const STEP_STYLES'), src.indexOf('\n', src.indexOf('const STEP_STYLES')));
  const STEP_STYLES = new Function(stepDecl + '\nreturn STEP_STYLES;')();
  const dsrc = fs.readFileSync(path.join(ROOT, 'web/src/dials.js'), 'utf8');
  const DIAL_STYLES = new Function(dsrc.slice(dsrc.indexOf('const DIAL_STYLES'), dsrc.indexOf(';', dsrc.indexOf('const DIAL_STYLES')) + 1) + '\nreturn DIAL_STYLES;')();
  const DIAL_DEFAULT = /const DIAL = \{ style: '([a-z]+)'/.exec(dsrc)[1];
  fs.writeFileSync(path.join(ROOT, 'native/Sources/VekturDrumCore/Appearance+Generated.swift'), `// Generated by tools/gen_manual.js from web/src/appearance.js — do not edit.
// The colour themes of SETTINGS → APPEARANCE, identical to the web app's. Colours are "#rrggbb".

public struct AppearanceTheme: Sendable, Identifiable, Hashable {
    public let id: String, name: String
    public let led: String, display: String, arc: String   // lit LEDs / steps / pads · displays & selection · dial arcs
    public let chassis: String, strip: String              // keys of AppearanceTheme.chassis / .strips
}

extension AppearanceTheme {
    public static let all: [AppearanceTheme] = [
${THEMES.map(([id, name, t]) => `        AppearanceTheme(id: ${sw(id)}, name: ${sw(name)}, led: ${sw(t.led)}, display: ${sw(t.disp)}, arc: ${sw(t.arc)}, chassis: ${sw(t.chassis)}, strip: ${sw(t.strip)}),`).join('\n')}
    ]
    /// Chassis tones: name, then top, upper, body, section top, section bottom, page.
    public static let chassis: [String: (name: String, colors: [String])] = [
${Object.entries(CHASSIS).map(([k, v]) => `        ${sw(k)}: (${sw(v[0])}, [${v.slice(1).map(sw).join(', ')}]),`).join('\n')}
    ]
    /// Top strips: name, then light, mid, dark, lettering.
    public static let strips: [String: (name: String, colors: [String])] = [
${Object.entries(STRIPS).map(([k, v]) => `        ${sw(k)}: (${sw(v[0])}, [${v.slice(1).map(sw).join(', ')}]),`).join('\n')}
    ]
    /// Dial designs (id, name, family); NEW (0.9.1): the default is ${DIAL_DEFAULT}.
    public static let dialStyles: [(id: String, name: String, family: String)] = [
${DIAL_STYLES.map(([id, n, f]) => `        (${sw(id)}, ${sw(n)}, ${sw(f)}),`).join('\n')}
    ]
    public static let defaultDialStyle = ${sw(DIAL_DEFAULT)}
    /// NEW (0.9.1): sequencer step designs (id, name, description); classic is the default.
    public static let stepStyles: [(id: String, name: String, description: String)] = [
${STEP_STYLES.map(([id, n, d]) => `        (${sw(id)}, ${sw(n)}, ${sw(d)}),`).join('\n')}
    ]
    public static let defaultStepStyle = "classic"
}
`);
  console.log(`appearance: ${THEMES.length} themes, ${DIAL_STYLES.length} dials (default ${DIAL_DEFAULT}), ${STEP_STYLES.length} step designs, ${Object.keys(CHASSIS).length} chassis, ${Object.keys(STRIPS).length} strips → Swift`);
}
