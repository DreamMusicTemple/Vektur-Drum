#!/usr/bin/env node
// Vektur Drum — one parameter specification for every code base.
//   node tools/gen_native_params.js
// Source: web/src/params.js (which builds on Vektur VJ's tools/drumspec.py table, verbatim). Writes:
//   native/Sources/VekturDrumDSP/vd_params.generated.h      C++ table + dense indices for the engine
//   native/Sources/VekturDrumCore/ParameterSpec+Generated.swift   Swift specs for the app, AU parameter tree, presets
// Dense indices (engine-internal, = web) are mapped to the stable addresses of vd_engine.h, which never change.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'web/src/params.js'), 'utf8');
const X = new Function(src + '\nreturn { DRUM_PARAMS, DRUM_NOTES, DRUM_DIV_BEATS, DRUM_DEF_DIV, DRUM_TRACKS, SL_DIV_BEATS, SL_STUTTER_N, SL_SLOTS, SL_ACTIONS, SL_SHORT, SL_HOLD, SL_DIVS, MOD_SOURCES, MOD_WIRES, RING_OSC, SAMPLER_MODELS, RS_MODES, TS_MODES };')();
const P = X.DRUM_PARAMS;

// ---- stable addresses (vd_engine.h)
const TRACK_BASE = 1024, TRACK_STRIDE = 256, LFO_BASE = 48, LFO_STRIDE = 8;
const TRACK_LOCAL = { engine: 32, choke: 33, sweep: 35, swtime: 36,
  fmalgo: 64, fmfreq: 65, fmratio: 66, fmratio2: 67, fmindex: 68, fmidec: 69, fmfb: 70, fmfold: 71, fmnoise: 72,
  eq1f: 40, eq1g: 41, eq2f: 42, eq2g: 43, eq3f: 44, eq3g: 45, eq4f: 46, eq4g: 47,   // NEW: 4-band EQ
  metal: 48, rsmp: 49, rsmode: 50, rssens: 51, slice: 52, tsmode: 53, stretch: 54, smodel: 55,
  long: 56 };   // NEW (0.9.1): long sounds   // NEW (0.9): Metalise, Resample, slices, stretch
const MASTER = { 'dr.ch': 0, 'dr.swing': 1, 'dr.temper': 2, 'dr.level': 3, 'dr.choke': 4, 'dr.dlydiv': 5, 'dr.dlyfb': 6, 'dr.dlytone': 7,
  'dr.dlypp': 8, 'dr.revsize': 9, 'dr.revdamp': 10, 'gl.on': 32, 'gl.mode': 33, 'gl.mix': 34, 'gl.size': 35, 'gl.speed': 36, 'gl.metal': 37, 'gl.chance': 38, 'gl.chdiv': 39,
  // NEW: Slicer 80–91, envelope follower 96–99, chaos 104–105
  'sl.on': 80, 'sl.mix': 81, 'sl.div': 82, 'sl.bars': 83, 'sl.density': 84, 'sl.evolve': 85, 'sl.seed': 86, 'sl.speed': 87, 'sl.stutter': 88,
  'sl.tape': 89, 'sl.pitch': 90, 'sl.hold': 91, 'env.src': 96, 'env.att': 97, 'env.rel': 98, 'env.gain': 99, 'ch.mode': 104, 'ch.rate': 105,
  'tp.wow': 112, 'tp.flutter': 113, 'tp.dust': 114,
  'dr.revtype': 11, 'dr.human': 12, 'in.level': 120, 'in.dly': 121, 'in.rev': 122, 'in.drums': 123 };   // NEW (0.8): temper replaces warmth at 2 (bipolar)   // NEW: tape and vinyl
const LFO_F = ['rate', 'shape', 'depth', 'dest', 'sync', 'div'];
const tmpl = P.filter(p => p[0].startsWith('t1.')).map(p => p[0].slice(3));
const local = k => { const i = tmpl.indexOf(k); return i < 15 ? i : TRACK_LOCAL[k]; };
function address(key) {
  let m = key.match(/^t(\d+)\.(\w+)$/);
  if (m) return TRACK_BASE + (+m[1] - 1) * TRACK_STRIDE + local(m[2]);
  if (key in MASTER) return MASTER[key];
  m = key.match(/^lfo(\d)\.(\w+)$/);
  if (m) return LFO_BASE + (+m[1] - 1) * LFO_STRIDE + LFO_F.indexOf(m[2]);
  throw new Error('no address for ' + key);
}
tmpl.forEach(k => { if (local(k) == null) throw new Error('no local index for ' + k); });
const addrs = P.map(p => address(p[0]));
if (new Set(addrs).size !== addrs.length) throw new Error('duplicate addresses');

const cid = k => k.toUpperCase().replace(/\./g, '_');
const f = v => { const s = String(Math.fround(v)); return (/[.e]/.test(s) ? s : s + '.0') + 'f'; };
const stride = P.findIndex(p => p[0] === 't2.model');

// ---- C++
let h = `// Generated by tools/gen_native_params.js from web/src/params.js — do not edit.
// Dense indices are the engine's (identical to the web engine); vd_param_address() gives the stable vd_engine.h address.
#pragma once
#include <stdint.h>

#define VDG_PARAM_COUNT ${P.length}
#define VDG_TRACKS ${X.DRUM_TRACKS}
#define VDG_TRACK_STRIDE ${stride}
#define VDG_DIVS ${X.DRUM_DIV_BEATS.length}
#define VDG_DEF_DIV ${X.DRUM_DEF_DIV}

/* per-track template: dense index of track t's parameter k = VDG_T1 + t * VDG_TRACK_STRIDE + VDG_K_<k> */
enum { VDG_T1 = 0,
${tmpl.map((k, i) => `    VDG_K_${cid(k)} = ${i},`).join('\n')}
};
/* master, glitch and LFO parameters (dense indices) */
enum {
${P.map((p, i) => [p[0], i]).filter(([k]) => !/^t\d\./.test(k)).map(([k, i]) => `    VDG_${cid(k)} = ${i},`).join('\n')}
};
typedef struct { const char *key; float min, max, def; uint8_t smooth, logscale, modulatable; uint32_t address; } vdg_param;   /* modulatable: a modulation-matrix destination */
static const vdg_param kVDGParams[VDG_PARAM_COUNT] = {
${P.map((p, i) => `    {"${p[0]}", ${f(p[4])}, ${f(p[5])}, ${f(p[6])}, ${p[3] === 'cont' ? 1 : 0}, ${p[7] === 'log' ? 1 : 0}, ${p[3] === 'cont' || (p[3] === 'int' && p[0] !== 'dr.ch') || p[0] === 'gl.on' ? 1 : 0}, ${addrs[i]}},`).join('\n')}
};
static const double kVDGDivBeats[VDG_DIVS] = {${X.DRUM_DIV_BEATS.join(', ')}};
static const int kVDGNotes[VDG_TRACKS] = {${X.DRUM_NOTES.join(', ')}};
static const double kVDGSlDivBeats[${X.SL_DIV_BEATS.length}] = {${X.SL_DIV_BEATS.join(', ')}};
static const int kVDGSlStutter[${X.SL_STUTTER_N.length}] = {${X.SL_STUTTER_N.join(', ')}};
#define VDG_SL_SLOTS ${X.SL_SLOTS}
#define VDG_SL_ACTIONS ${X.SL_ACTIONS.length}
#define VDG_MOD_SOURCES ${X.MOD_SOURCES.length}
#define VDG_MOD_WIRES ${X.MOD_WIRES}
#define VDG_RING_OSC ${X.RING_OSC}
/* NEW (0.9): RESAMPLE's sampler models — bits, converter rate, reconstruction (0 hold, 1 linear, 2 drop-sample), input filter × rate, emphasis, converter curve, noise */
#define VDG_SMODELS ${X.SAMPLER_MODELS.length}
static const double kVDGSModels[VDG_SMODELS][7] = {
${X.SAMPLER_MODELS.map(m => `    {${m.slice(1).join(', ')}},   /* ${m[0]} */`).join('\n')}
};
`;
fs.writeFileSync(path.join(ROOT, 'native/Sources/VekturDrumDSP/vd_params.generated.h'), h);

// ---- Swift
const kind = { cont: 'continuous', int: 'integer', enum: 'choice', bool: 'toggle' }, scale = { lin: 'linear', log: 'logarithmic' };
const sw = s => JSON.stringify(s);
const entry = (p, key, index) => `        ParameterSpec(key: ${sw(key)}, index: ${index}, name: ${sw(p[1])}, kind: .${kind[p[3]]}, range: ${+p[4]}...${+p[5]}, defaultValue: ${+p[6]}, scale: .${scale[p[7]]}, unit: ${sw(p[8])}, choices: [${p[9].map(sw).join(', ')}]),`;
const t1 = P.filter(p => p[0].startsWith('t1.'));
const master = P.filter(p => !/^t\d\./.test(p[0]));
const defaults = [];
for (let t = 1; t <= X.DRUM_TRACKS; t++) defaults.push(P.filter(p => p[0].startsWith(`t${t}.`)).map(p => `${sw(p[0].slice(3))}: ${+p[6]}`).join(', '));
const swift = `// Generated by tools/gen_native_params.js from web/src/params.js — do not edit.
// The per-track template (index = track-local address in vd_engine.h) and the master block (index = master address).

extension ParameterSpec {
    /// Every parameter a track has: Vektur Pulse's 15 (indices 0–14), then engine, choke, sweep and FM.
    public static let track: [ParameterSpec] = [
${t1.map(p => entry(p, p[0].slice(3), local(p[0].slice(3)))).join('\n')}
    ]

    /// Master section, glitch and the three LFOs (key as in kits: "dr.swing", "gl.mix", "lfo2.rate" …).
    public static let master: [ParameterSpec] = [
${master.map((p, i) => entry(p, p[0], address(p[0]))).join('\n')}
    ]

    /// Default values per track (they differ: model, decay, level, pan, and the FM tracks 8–9).
    public static let trackDefaults: [[String: Double]] = [
${defaults.map(d => `        [${d}],`).join('\n')}
    ]

    /// MIDI notes of tracks 1–${X.DRUM_TRACKS} (GM: kick, snare, closed hat, open hat, clap, low tom, side stick, cowbell, crash, high-mid tom, ride, tambourine).
    public static let trackNotes: [Int] = [${X.DRUM_NOTES.join(', ')}]
}

/// NEW: names and sizes for the Slicer, the modulation matrix and ring modulation (same as the web app).
public enum DrumLists {
    public static let slicerActions: [String] = [${X.SL_ACTIONS.map(sw).join(', ')}]
    public static let slicerShort: [String] = [${X.SL_SHORT.map(sw).join(', ')}]
    public static let slicerHold: [String] = [${X.SL_HOLD.map(sw).join(', ')}]
    public static let slicerDivisions: [String] = [${X.SL_DIVS.map(sw).join(', ')}]
    public static let slicerDivisionBeats: [Double] = [${X.SL_DIV_BEATS.join(', ')}]
    public static let slicerSlots = ${X.SL_SLOTS}
    public static let modSources: [String] = [${X.MOD_SOURCES.map(sw).join(', ')}]
    public static let modSourceIDs: [String] = ["lfo1", "lfo2", "lfo3", "env", "chaos"]
    public static let modWires = ${X.MOD_WIRES}
    public static let ringOscillator = ${X.RING_OSC}   // ring master 0–${X.RING_OSC - 1} = tracks 1–${X.RING_OSC}, ${X.RING_OSC} = the sine oscillator
    /// NEW (0.9): RESAMPLE's sampler models, transient modes and the sample tune modes
    public static let samplerModels: [String] = [${X.SAMPLER_MODELS.map(m => sw(m[0])).join(', ')}]
    public static let transientModes: [String] = [${X.RS_MODES.map(sw).join(', ')}]
    public static let tuneModes: [String] = [${X.TS_MODES.map(sw).join(', ')}]
}
`;
fs.writeFileSync(path.join(ROOT, 'native/Sources/VekturDrumCore/ParameterSpec+Generated.swift'), swift);
console.log(`${P.length} parameters (${X.DRUM_TRACKS} tracks × ${stride} + ${master.length}) → C++ and Swift`);
