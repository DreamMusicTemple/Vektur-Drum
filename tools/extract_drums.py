#!/usr/bin/env python3
"""
Vektur Drum — reproducible extraction of the drum machine ("Vektur Pulse") from the Vektur VJ web build.

    python3 -I tools/extract_drums.py <path/to/VekturVJ/index.html> <out/index.html>

Every block is located by its section marker in the Vektur VJ source (never by line number), copied verbatim,
and checked: if a marker is missing or matches more than once, extraction stops. The only edits to extracted
code are the PATCHES below — each must match exactly once and each states why it exists. Everything that is not
extracted (the standalone host) lives in reference/web/host.js and host.css and is clearly marked as new code.

Vektur VJ is only read, never written.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
WEB = HERE.parent / "reference" / "web"


def die(msg):
    sys.exit("extract_drums: " + msg)


class Source:
    def __init__(self, text):
        self.text = text
        self.lines = text.split("\n")

    def _find_line(self, marker, start=0):
        hits = [i for i, l in enumerate(self.lines) if marker in l and i >= start]
        if not hits:
            die(f"marker not found: {marker!r}")
        return hits

    def unique_line(self, marker):
        hits = self._find_line(marker)
        if len(hits) != 1:
            die(f"marker matches {len(hits)} lines (expected 1): {marker!r}")
        return hits[0]

    def block(self, begin, end, include_end=False):
        """Lines from the one line containing `begin` up to (not including) the first line after it containing `end`."""
        a = self.unique_line(begin)
        b = self._find_line(end, a + 1)[0]
        return "\n".join(self.lines[a : b + (1 if include_end else 0)])

    def line(self, marker):
        return self.lines[self.unique_line(marker)]

    def function(self, header):
        """A top-level function: from its header line to the first following line that is exactly '}'."""
        a = self.unique_line(header)
        for j in range(a, len(self.lines)):
            if self.lines[j] == "}" or (j == a and self.lines[j].rstrip().endswith("}") and self.lines[j].count("{") == self.lines[j].count("}")):
                return "\n".join(self.lines[a : j + 1])
        die(f"end of function not found: {header!r}")


# (block name, old text, new text, reason) — each old text must occur exactly once in its block.
PATCHES = [
    ("params", 'const DRUM_NAME = "Vektur Pulse";', 'const DRUM_NAME = "Vektur Drum";',
     "Product name. The preset file format id stays 'vektur-pulse-presets' so kits move between Vektur VJ and Vektur Drum."),
    ("panel", "top.append(exp, hbtn('CLOSE', 'sm', closeDrums));",
     "/* Vektur Drum: the panel is the whole app — no DOCK / EXPAND / CLOSE (extract_drums.py patch) */",
     "In Vektur VJ the drums are a bottom sheet over the visuals; standalone, the panel is the app."),
    ("panel", "dKnob(mk, 'dr.swing', 'Swing');",
     "hostTempoKnob(mk); dKnob(mk, 'dr.swing', 'Swing');",
     "Vektur VJ's tempo comes from the VJ clock. Standalone, the drum machine needs its own tempo control (host.js)."),
]


def apply_patches(name, text):
    for blk, old, new, _why in PATCHES:
        if blk != name:
            continue
        n = text.count(old)
        if n != 1:
            die(f"patch for block '{name}' matches {n} times: {old!r}")
        text = text.replace(old, new)
    return text


def main():
    if len(sys.argv) != 3:
        die("usage: extract_drums.py <VekturVJ index.html> <out index.html>")
    src = Source(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))

    js = {}
    # ---- shared helpers the drum code calls (verbatim)
    js["helpers"] = "\n".join([
        src.line("const $ = (s, r = document) => r.querySelector(s);"),
        src.line("const clamp = (v, a, b) => Math.min(b, Math.max(a, v));"),
        src.line("function el(tag, cls, html) {"),
        src.line("function toast(msg) {"),
        src.line("let midiLearn = false, learnPath = null;"),
        src.block("function slider(host, o) {", "/** Angle parameters (Yaw, Pitch, Bank, Rotate)"),
        src.line("function synthNorm(q, v) {"),
        src.line("function synthDenorm(q, t) {"),
        src.function("function synthFmt(q, v) {"),
        src.line("function ufontB64(bytes) {"),
        src.line("function ufontBytes(b64) {"),
    ])
    # ---- the drum machine itself (verbatim)
    js["params"] = src.block("/* DRUM_PARAMS:BEGIN", "/* DRUM_PARAMS:END */", include_end=True)
    js["engine"] = src.block("VEKTUR PULSE — drum synth + step sequencer (web engine)", "VEKTUR SPECTRA — audio wiring, panel, keyboard, MIDI")
    js["panel"] = src.block("VEKTUR PULSE — drum machine: state, engine sync, panel (web build)", "Generated by tools/soundpresets.py")
    js["factory"] = src.line("const DRUM_FACTORY = [")
    js["presets"] = src.block("PRESETS — Vektur Spectra sounds and Vektur Pulse kits", "IMPORTED FONTS — your own fonts for text clips")
    js["samples"] = src.block("VEKTUR PULSE — samples on tracks", "Generated by tools/linkpresets.py")
    # the worklet's drum message dispatch, so the standalone processor speaks the same protocol
    dispatch = src.block("if (d.dr) { const r = s.drums, a = d.dr;", "  process(inputs, outputs) {")
    dispatch = dispatch.rsplit("\n", 1)[0]  # drop the constructor's closing '  }'
    dispatch = dispatch.replace("const r = s.drums, a = d.dr;", "const r = this.r, a = d.dr;", 1)
    js["dispatch"] = dispatch

    for k in list(js):
        js[k] = apply_patches(k, js[k])

    # ---- styles (verbatim): theme, base, modal/sheet, buttons, toast, help text, knob widget
    css = "\n".join([
        ":root{",
        src.block("  --bg:#121410;--panel:#1F221A;", "  --scale:1;"),
        "}",
        src.line("html{font-size:calc(13px * var(--scale))"),
        src.line("*{box-sizing:border-box}"),
        src.line("html,body{margin:0;height:100%;background:var(--bg)"),
        src.line("button{font:inherit;color:inherit;cursor:pointer}"),
        src.line("input,select{font:inherit}"),
        src.line(".spacer{flex:1}"),
        src.line(".cbtn{height:2.4rem;"),
        src.line(".cbtn.on{"),
        src.line(".sheet{width:min(46rem,94vw)"),
        src.line(".sheet h2{"),
        src.line(".sheet h4{"),
        src.line(".modal{position:fixed;inset:0;"),
        src.line(".modal.open{display:flex}"),
        src.line(".toast{position:fixed;"),
        src.line(".toast.on{opacity:1}"),
        src.line(".clhelp{font-size:.8rem;"),
        src.block(".kcell{display:flex;", ".knob.learn u{", include_end=True),
    ])

    host_js = (WEB / "host.js").read_text(encoding="utf-8")
    host_css = (WEB / "host.css").read_text(encoding="utf-8")
    worklet = (WEB / "worklet.js").read_text(encoding="utf-8").replace("/*@DISPATCH@*/", js["dispatch"])

    order = ["helpers", "params", "engine", "panel", "factory", "presets", "samples"]
    body = "\n\n".join(f"/* ---- extracted from Vektur VJ: {k} ---- */\n{js[k]}" for k in order)
    stamp = json.dumps({"source": pathlib.Path(sys.argv[1]).name, "patches": [p[3] for p in PATCHES]}, ensure_ascii=False)

    page = f"""<!doctype html>
<html lang="en"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Vektur Drum">
<meta name="theme-color" content="#0c0d0e">
<title>Vektur Drum — reference build</title>
<!-- Generated by tools/extract_drums.py — do not edit; edit host.* or the patch list instead. {stamp} -->
<style>
{css}
{host_css}
</style>
</head><body>
<div class="toast" id="toast"></div>
<script>
/* Main-thread stand-ins for the AudioWorklet globals, so the same processor can also run on a ScriptProcessorNode
   when a page's security policy blocks AudioWorklet modules (host.js decides which one runs). */
var sampleRate = 48000, VD_PROCESSOR = null;
class AudioWorkletProcessor {{ constructor() {{ this.port = {{ onmessage: null, postMessage: m => {{ if (this.port.toHost) this.port.toHost(m); }} }}; }} }}
function registerProcessor(name, cls) {{ VD_PROCESSOR = cls; }}
</script>
<script id="vd-worklet">
{worklet}
</script>
<script>
'use strict';
{body}

/* ======================================================================== standalone host (new code: host.js) */
{host_js}
</script>
</body></html>
"""
    pathlib.Path(sys.argv[2]).write_text(page, encoding="utf-8")
    sizes = {k: len(v) for k, v in js.items()}
    print("extracted:", json.dumps(sizes), "→", sys.argv[2], f"({len(page):,} bytes)")


if __name__ == "__main__":
    main()
