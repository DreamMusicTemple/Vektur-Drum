/** Vektur Pulse kits and projects → Vektur Drum: the master hat choke becomes choke group A on tracks 3–4 (or none),
    and a track that had a sample plays it through the Sample engine. Keys already present are left alone. */
function drumMigrateParams(p, smp) {
  for (const t of [3, 4]) if (p[`t${t}.choke`] == null) p[`t${t}.choke`] = p['dr.choke'] === 0 ? 0 : 1;
  (smp || []).forEach((k, i) => { if (k && p[`t${i + 1}.engine`] == null) p[`t${i + 1}.engine`] = 1; });
  return p;
}
