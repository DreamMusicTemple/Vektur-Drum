/* ============================================================ PRESETS — Vektur Spectra sounds and Vektur Pulse kits
   16 factory presets each (web/sound-presets.js, generated by tools/soundpresets.py) and 16 slots of your own each,
   saved with the set (S.synth.user / S.drums.user, plus the name of the last loaded preset in .preset). A synth preset
   is the sound; a drum preset is the kit with its 8 patterns and chain. Presets never change the MIDI channel.
   Export writes a .json file (one preset or all of yours); import fills your empty slots. Same JSON as the iPad app. */
const PRESET_SLOTS = 16;
const PRE = { kind: 'synth', sel: null, bank: 0, cat: 'All' };   // sel: { src: 'f' | 'u', i } · bank: 0 = the set's 16 slots, 1–20 = NEW user banks
/* NEW: 20 user banks of 99 presets each, on the device (IndexedDB, 'bank:N'; on iOS the app group, shared with the AUv3),
   so they're there in every set. The set's own 16 slots stay as they were (they travel with the set). */
const BANK_N = 20, BANK_SLOTS = 99;
const BANKS = { list: new Array(BANK_N + 1).fill(null), loaded: false, loading: null };
function bankEmpty(b) { return { name: 'Bank ' + String(b).padStart(2, '0'), slots: new Array(BANK_SLOTS).fill(null) }; }
function bankGet(b) { if (!BANKS.list[b]) BANKS.list[b] = bankEmpty(b); return BANKS.list[b]; }
function bankClean(b, o) { const k = bankEmpty(b); if (o && typeof o === 'object') { if (typeof o.name === 'string' && o.name.trim()) k.name = o.name.trim().slice(0, 40);
  if (Array.isArray(o.slots)) for (let i = 0; i < BANK_SLOTS; i++) k.slots[i] = o.slots[i] ? presetClean('drums', o.slots[i]) : null; } return k; }
function banksLoad() {
  if (BANKS.loaded) return Promise.resolve(); if (BANKS.loading) return BANKS.loading;
  return BANKS.loading = (async () => { for (let b = 1; b <= BANK_N; b++) { try { const r = await fileGet('bank:' + b); if (r && r.blob) BANKS.list[b] = bankClean(b, JSON.parse(await r.blob.text())); } catch (e) { } } BANKS.loaded = true; })();
}
async function bankSave(b) { const k = bankGet(b); try { await filePut('bank:' + b, new Blob([JSON.stringify(k)], { type: 'application/json' }), k.name); } catch (e) { toast('Could not save the bank: ' + e.message); } }
function bankCount(b) { const k = BANKS.list[b]; return k ? k.slots.filter(Boolean).length : 0; }
/** After a change to the slots on show: the set's slots save with the set, a bank saves to the device. */
function presetStore(kind) { if (kind === 'drums' && PRE.bank > 0) bankSave(PRE.bank); else dirty(); }
const PRESET_FMT = { synth: 'vektur-spectra-presets', drums: 'vektur-pulse-presets' };
const PRESET_NAME = { synth: () => SPECTRA_NAME, drums: () => DRUM_NAME };

function presetState(kind) { return kind === 'synth' ? synthState() : drumState(); }
function presetUser(kind) {
  if (kind === 'drums' && PRE.bank > 0) return bankGet(PRE.bank).slots;
  const st = presetState(kind);
  if (!Array.isArray(st.user)) st.user = [];
  while (st.user.length < PRESET_SLOTS) st.user.push(null);
  st.user.length = PRESET_SLOTS;
  return st.user;
}
function presetFactory(kind) { return kind === 'synth' ? SYNTH_FACTORY : DRUM_FACTORY; }

// ---- cleaning (anything read from a file or an old set): only known parameters, in range; patterns in shape
function presetCleanP(kind, p) {
  const out = {}, P = kind === 'synth' ? SPECTRA_PARAMS : DRUM_PARAMS, ID = kind === 'synth' ? SP_ID : DP_ID, skip = kind === 'synth' ? 'midi.ch' : 'dr.ch';
  if (p && typeof p === 'object') for (const k of Object.keys(p)) {
    const q = P[ID[k]]; const v = +p[k];
    if (!q || k === skip || !isFinite(v)) continue;
    out[k] = q[3] === 'cont' ? clamp(v, q[4], q[5]) : Math.round(clamp(v, q[4], q[5]));
  }
  // 0.8: master Warmth (0…1) became TEMPER (−1 warm … +1 cold). An old value keeps its sound on the warm side.
  if (kind === 'drums' && p && typeof p === 'object' && out['dr.temper'] == null && p['dr.warmth'] != null && isFinite(+p['dr.warmth'])) out['dr.temper'] = -clamp(+p['dr.warmth'], 0, 1);
  return out;
}
/** One step from any version → the current array, trimmed to the shortest form that keeps it (4, 9, 14, 15, 20 or 24 values).
    oldRing: written before 0.9, when the ring's sine oscillator was master 9 (it is RING_OSC = 12 now). */
const DRUM_STEP_LENS = [9, 14, 15, 20, 24];   // a step is written at the shortest of these that keeps its values (9 = the 0.6 step)
function drumCleanStep(s, oldRing) {
  if (!Array.isArray(s)) return null;
  const nm = (i, lo, hi, d) => s.length > i && s[i] != null && isFinite(+s[i]) ? clamp(+s[i], lo, hi) : d;
  const v = [nm(0, 0, 1, .8) || .8, nm(1, -1, 1, 0), Math.round(nm(2, -12, 12, 0)), Math.round(nm(3, 1, 4, 1)) || 1,
    nm(4, 0, 1, 0), nm(5, 0, 1, 0), nm(6, 0, 1, 0), nm(7, 0, 1, 1), nm(8, 0, 16, 0) > 0 ? clamp(+s[8], .25, 16) : 0];
  const rg = nm(9, 0, 1, 0) > 0;
  let m = Math.round(nm(10, 0, 99, RING_OSC)); if (oldRing && m >= 9) m = RING_OSC; m = clamp(m, 0, RING_OSC);
  if (rg) v.push(1, m, Math.round(nm(11, 0, (1 << DRUM_TRACKS) - 1, 0)), nm(12, 0, 1, 1), nm(13, 20, 5000, 220)); else v.push(...DRUM_STEP_DEF.slice(9, 14));
  v.push(nm(14, 0, 1, 0), Math.round(nm(15, -24, 24, 0)), nm(16, 0, 1, 1), nm(17, 0, 1, 0), nm(18, 0, 1, 0), nm(19, 0, 1, 1));
  const met = nm(20, -1, 1, -1); v.push(met < 0 ? -1 : met, Math.round(nm(21, 0, 32, 0)), nm(22, 0, 1, 0), nm(23, 0, 1, 0));
  return drumTrimStep(v);
}
function drumTrimStep(v) {
  let last = 3; for (let i = 4; i < DRUM_STEP_N; i++) if (v[i] !== DRUM_STEP_DEF[i]) last = i;
  const L = DRUM_STEP_LENS.find(n => n > last) || DRUM_STEP_N; return v.slice(0, L);
}
function presetCleanPattern(pt, oldRing) {
  const e = drumEmptyPattern(); if (!pt || typeof pt !== 'object') return e;
  const b = +pt.bars; e.bars = b >= 4 ? 4 : b >= 2 ? 2 : 1;
  e.sl = pt.sl === 0 || pt.sl === 1 ? pt.sl : -1;   // NEW (0.9): this pattern's Slicer — −1 follows SLICER, 0 off, 1 on
  for (let t = 0; t < DRUM_TRACKS; t++) {
    const src = Array.isArray(pt.tr) ? pt.tr[t] : null; if (!src) continue;
    const tr = e.tr[t];
    tr.len = clamp(Math.round(+src.len || 16), 1, 16); tr.div = clamp(Math.round(src.div != null ? +src.div : DRUM_DEF_DIV), 0, DRUM_DIVS.length - 1);
    for (let k = 0; k < 16; k++) tr.s[k] = drumCleanStep(Array.isArray(src.s) ? src.s[k] : null, oldRing);
  }
  return e;
}
function presetClean(kind, o) {
  if (!o || typeof o !== 'object') return null;
  const pr = { name: String(o.name || 'Preset').trim().slice(0, 60) || 'Preset', p: presetCleanP(kind, o.p) };
  if (o.cat) pr.cat = String(o.cat).slice(0, 30);
  if (kind === 'drums' && o.bpm != null && isFinite(+o.bpm) && +o.bpm > 0) pr.bpm = Math.round(clamp(+o.bpm, 40, 240) * 10) / 10;   // NEW (0.8): a kit's own tempo
  if (kind === 'drums' && o.init) pr.init = true;
  if (kind === 'drums') {
    const oldRing = !(+o.v >= 2);   // kits written before 0.9 (ring oscillator = master 9)
    pr.pats = (Array.isArray(o.pats) ? o.pats : []).slice(0, 8).map(x => presetCleanPattern(x, oldRing)); pr.v = 2;
    if (Array.isArray(o.sx)) pr.sx = Array.from({ length: DRUM_TRACKS }, (_, i) => drumSxClean(o.sx[i]));   // NEW (0.9): per-track slices, transients, BPM
    if (!pr.pats.length) pr.pats = [drumEmptyPattern()];
    pr.chain = (Array.isArray(o.chain) ? o.chain : []).slice(0, 16).map(c => clamp(Math.round(+c || 0), 0, 7));
    pr.chainOn = !!o.chainOn;
    if (o.ntr != null) pr.ntr = clamp(Math.round(+o.ntr) || DRUM_TRACKS, 6, DRUM_TRACKS);   // Vektur Pulse kits have none: they keep the current count
    pr.smp = Array.from({ length: DRUM_TRACKS }, (_, i) => Array.isArray(o.smp) && typeof o.smp[i] === 'string' ? o.smp[i].slice(0, 12) : null);   // track samples (keys)
    if (Array.isArray(o.slice)) pr.slice = drumSliceClean(o.slice);   // NEW: the Slicer program
    if (Array.isArray(o.wires)) pr.wires = drumWiresClean(o.wires);   // NEW: the modulation wires
    if (Array.isArray(o.lfo)) pr.lfo = drumLfoClean(o.lfo);   // NEW (0.9.1): drawn LFO shapes
    if (Array.isArray(o.smpMeta)) pr.smpMeta = o.smpMeta.filter(f => f && typeof f.key === 'string').slice(0, DRUM_TRACKS).map(f => ({ key: f.key.slice(0, 12), name: String(f.name || 'Sample').slice(0, 40), fmt: f.fmt === 'flac' ? 'flac' : 'wav' }));
  }
  return pr;
}

// ---- capture / apply
function presetCapture(kind, name) {
  const st = presetState(kind);
  const pr = { name: String(name).trim().slice(0, 60) || 'My preset', p: presetCleanP(kind, st.p) };
  if (kind === 'drums') { pr.pats = JSON.parse(JSON.stringify(st.pats)); pr.chain = st.chain.slice(); pr.chainOn = !!st.chainOn; pr.smp = drumSmp().slice(); pr.ntr = st.ntr; pr.v = 2; pr.sx = JSON.parse(JSON.stringify(drumSx()));
    pr.slice = drumSliceProg().map(s => s.slice()); pr.wires = drumWires().map(w => Object.assign({}, w)); pr.lfo = drumLfoPts().map(p => p.slice());
    pr.smpMeta = pr.smp.filter(Boolean).map(k => drumLib().find(f => f.key === k)).filter(Boolean).map(f => ({ key: f.key, name: f.name, fmt: f.fmt })); }
  return pr;
}
async function presetApply(kind, pr) {
  const st = presetState(kind);
  if (kind === 'synth') {
    const ch = st.p['midi.ch']; st.p = Object.assign({}, pr.p); if (ch != null) st.p['midi.ch'] = ch;
    st.preset = pr.name;
    synthPanic(); synthPushAll();
    if (!st.on) await synthSetOn(true);
    if (typeof synthOpen === 'function' ? synthOpen() : ($('#synthModal') && $('#synthModal').classList.contains('open'))) renderSynth();
  } else {
    const ch = st.p['dr.ch']; st.p = drumMigrateParams(Object.assign({}, pr.p), pr.smp); if (ch != null) st.p['dr.ch'] = ch;
    if (pr.ntr != null) { st.ntr = clamp(Math.round(+pr.ntr), 6, DRUM_TRACKS); drumPost(['n', st.ntr]); }
    const pats = (pr.pats || []).slice(0, 8).map(x => presetCleanPattern(x, !(pr.v >= 2))); while (pats.length < 8) pats.push(drumEmptyPattern());   // copies, and pads 6-track Pulse kits to 9 tracks
    st.pats = pats; st.chain = (pr.chain || []).slice(0, 16); st.chainOn = !!pr.chainOn; st.sel = 0; st.preset = pr.name;
    st.slice = drumSliceClean(pr.slice); st.wires = drumWiresClean(pr.wires); st.lfo = drumLfoClean(pr.lfo);   // NEW (kits without them: a clear program, no wires)
    (pr.smpMeta || []).forEach(f => { if (!drumLib().some(x => x.key === f.key)) drumLib().push({ key: f.key, name: f.name, fmt: f.fmt }); });   // bank kits: bytes come from the device store
    st.smp = Array.from({ length: DRUM_TRACKS }, (_, i) => { const k = pr.smp && pr.smp[i]; return k && drumLib().some(f => f.key === k) ? k : null; });   // factory kits: none
    st.sx = Array.from({ length: DRUM_TRACKS }, (_, i) => drumSxClean(Array.isArray(pr.sx) ? pr.sx[i] : null));   // NEW (0.9): slices travel with the kit
    drumSamplesPush(); if (pr.smpMeta && pr.smpMeta.length && typeof drumSamplesSync === 'function') drumSamplesSync();
    if (pr.bpm) setBpm(pr.bpm);   // a kit with its own tempo (the Ambient kits are slow)
    if (!st.on) await drumsSetOn(true); else drumPushAll();
    if (drumsOpen()) renderDrums();
  }
  dirty(); toast(pr.name + ' loaded');
  if (presetsOpen()) renderPresets();
}

// ---- files
function presetFile(kind, list, bank) {
  const o = { format: PRESET_FMT[kind], version: 1, presets: list }; if (bank) o.bank = bank;
  if (kind === 'drums') { const keys = new Set(list.flatMap(p => (p.smp || []).filter(Boolean))); const smp = drumLib().filter(f => keys.has(f.key) && f.data); if (smp.length) o.samples = smp; }   // the kits' sample files travel with them
  return JSON.stringify(o, null, 1);
}
function presetExport(kind, list, base, bank) {
  const ext = kind === 'synth' ? '.spectra.json' : '.pulse.json';
  downloadText(presetFile(kind, list.map(p => presetClean(kind, p)), bank), (base || 'presets').replace(/[^\w-]+/g, '_') + ext, 'application/json');
}
/** Reads a preset file's text: returns the cleaned presets, or an error message. */
function presetParse(kind, text) {
  let o; try { o = JSON.parse(text); } catch (e) { return 'That file is not a preset file.'; }
  const other = kind === 'synth' ? 'drums' : 'synth';
  if (o && o.format === PRESET_FMT[other]) return `That file holds ${PRESET_NAME[other]()} presets — import it in the ${PRESET_NAME[other]()} preset browser.`;
  const list = o && o.format === PRESET_FMT[kind] && Array.isArray(o.presets) ? o.presets : (o && o.p ? [o] : null);
  if (!list) return 'That file is not a ' + PRESET_NAME[kind]() + ' preset file.';
  const out = list.map(x => presetClean(kind, x)).filter(Boolean);
  if (kind === 'drums' && out.length) {   // sample files carried in the file: add them to the set; drop references to ones that aren't there
    const files = (Array.isArray(o.samples) ? o.samples : []).filter(f => f && typeof f.key === 'string' && typeof f.data === 'string');
    out.forEach(pr => { pr.smp = pr.smp.map(k => k && (drumLib().some(f => f.key === k) || files.some(f => f.key === k)) ? k : null); });
    const used = new Set(out.flatMap(pr => pr.smp.filter(Boolean)));
    files.forEach(f => { if (used.has(f.key) && !drumLib().some(x => x.key === f.key)) drumLib().push({ key: f.key, name: String(f.name || 'Sample').slice(0, 40), fmt: f.fmt === 'flac' ? 'flac' : 'wav', data: f.data }); });
  }
  return out.length ? out : 'That file has no presets in it.';
}
/** Puts presets into the empty slots, in order. Returns [added, skipped]. */
function presetAddToSlots(kind, list) {
  const u = presetUser(kind); let added = 0;
  for (const pr of list) { const i = u.indexOf(null); if (i < 0) break; u[i] = pr; added++; }
  return [added, list.length - added];
}
function presetImport(kind) {
  const inp = document.createElement('input'); inp.type = 'file'; inp.accept = '.json,application/json';
  inp.onchange = async () => {
    const f = inp.files && inp.files[0]; if (!f) return;
    const r = presetParse(kind, await f.text());
    if (typeof r === 'string') { toast(r); return; }
    const [a, s] = presetAddToSlots(kind, r);
    presetStore(kind); renderPresets();
    toast(a ? `Imported ${a} preset${a > 1 ? 's' : ''}` + (s ? ` · ${s} skipped: no empty slots` : '') : 'No empty slots: delete one of yours first');
  };
  inp.click();
}

